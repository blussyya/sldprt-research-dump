const tag=process.argv[2],STOP=+process.argv[3];
const {mk,L}=require('./track.js'),{G,F,c}=L,fs=require('fs');
const [B0,O]=c.surfaces;
const sp0=tag==='hp'?require('./fit_hp.js').spineOf({...B0},1e-12).curve:tag==='conv'?F.spineOf(B0,1e-10).curve:F.spineOf({...B0},1e-12).curve;
const T=mk(sp0);
const rT=G.surfaceInverse(O,c.end.p),r3=G.surfaceInverse(O,c.chart[3]);
const Tp=c.end.p,Lp=c.start.p;
const fw=T.march(r3.u,r3.v,[-1,2],p=>Math.min(5e-7,0.2*G.dist(p.p,Tp)),p=>G.dist(p.p,Tp)<STOP,4e6);
const bw=T.march(r3.u,r3.v,[1,-2],p=>Math.min(5e-7,0.2*Math.max(G.dist(p.p,Lp),1e-9)),p=>G.dist(p.p,Lp)<3e-10,4e6);
const curve=bw.reverse().concat(fw.slice(1));
fs.writeFileSync('true_'+tag+'.json',JSON.stringify(curve.map(q=>({u:q.u,v:q.v,p:q.p}))));
const last=curve[curve.length-1];
console.log(tag,'n',curve.length,'last dist to T',G.dist(last.p,Tp),'max|h|',Math.max(...curve.map(q=>Math.abs(q.h))),'last uv-rT',last.u-rT.u,last.v-rT.v);
const sv=rT.v-3e-3;let su=rT.u+0.306*(-3e-3);
const o1=T.march(su,sv,[0.3,1],p=>Math.min(5e-7,0.2*G.dist(p.p,Tp)),p=>G.dist(p.p,Tp)<STOP,4e6);
const o2=T.march(su,sv,[-0.3,-1],p=>5e-7,p=>G.dist(p.p,Tp)>1.5e-3,4e6);
const other=o2.reverse().concat(o1.slice(1));
fs.writeFileSync('other_'+tag+'.json',JSON.stringify(other.map(q=>({u:q.u,v:q.v,p:q.p}))));
console.log('other ends dist',G.dist(other[other.length-1].p,Tp));
