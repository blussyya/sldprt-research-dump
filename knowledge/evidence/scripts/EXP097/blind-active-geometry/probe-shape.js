'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib');
const CONV = '/home/user/solidworks-converters/src';
const modern = require(CONV + '/container/modern.js');
const xt = require(CONV + '/parasolid/xt.js');
const partition = require(CONV + '/parasolid/partition.js');
const native = require(CONV + '/brep/native.js');
const Proc = require(CONV + '/brep/procedural.js');
const MAX = 128 * 1024 * 1024;
const raw = new Uint8Array(fs.readFileSync(process.argv[2]));
const all = modern.isOLE2(raw) ? null : modern.decompressOpenSX(raw, b => zlib.inflateRawSync(b, { maxOutputLength: MAX }), b => zlib.inflateSync(b, { maxOutputLength: MAX }));
const P = process.argv[3];
const inner = partition.extractPrimary(raw, { [P]: all[P] }, undefined, {}).inner;
const parsed = xt.parse(inner, true, {});
console.log('parse error', parsed.error, 'nodes', parsed.nodes.length, 'hidden', (parsed.hidden || []).length);
const N = native.build(parsed);
console.log('native faces', N.faces.length, 'edges', N.edges.size, 'vertices', N.vertices.size);
const R = Proc.resolve(N);
console.log('resolved keys', Object.keys(R), JSON.stringify(R.report));
const e = [...R.edges.values()][0];
console.log('edge keys', Object.keys(e));
console.log('edge sample', JSON.stringify({ ...e, curve: e.curve && e.curve.type, pcurves: undefined }).slice(0, 400));
const f = R.faces[0];
console.log('face keys', Object.keys(f), 'surface type', f.surface.type, 'loops', f.loops.length);
console.log('loop0 coedges', JSON.stringify(f.loops[0].coedges.slice(0, 3)));
console.log('face types', [...new Set(R.faces.map(x => x.surface.type))].join(','));
console.log('edge curve types', [...new Set([...R.edges.values()].map(x => x.curve && x.curve.type))].join(','));
console.log('pcurve count', [...R.edges.values()].reduce((s, x) => s + (x.pcurves ? x.pcurves.length : 0), 0));
